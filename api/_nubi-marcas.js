// tipeo de UNA letra (>= 6 caracteres, la variante chica vende <= 10% de la grande y su título nombra a la grande, o no nombra a la chica y vende <= 5%: así NEOVET / NEOJET, dos marcas reales, no se juntan).
// Se regenera con el generador de la sesión (ver memoria nubi-parser-modelos) cuando aparezcan variantes nuevas.
const SUFIJOS = /\b(ARGENTINA|ARG|SA|S A|SRL|S R L|LTDA|INC|LLC|CO|CORP|OFICIAL|OFFICIAL|S A S|SAS)$/;
function claveMarca(b) {
  const p = String(b == null ? '' : b).normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase().replace(/[^A-Z0-9]+/g, ' ').trim();
  let q = p;
  while (SUFIJOS.test(q)) q = q.replace(SUFIJOS, '').trim();
  return (q || p).replace(/ /g, '');
}
